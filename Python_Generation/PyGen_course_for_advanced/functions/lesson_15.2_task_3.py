# Напишите функцию mean(), которая принимает произвольное количество аргументов и возвращает среднее арифметическое переданных в нее числовых (int или float) аргументов. Если числовых аргументов не будет, функция должна вернуть 0.
#
# Примечание 1. Обратите внимание: функция должна принимать не список, а именно произвольное количество аргументов.
#
# Примечание 2. Функция должна игнорировать аргументы всех типов, кроме int или float.
#
# Примечание 3. Вызывать функцию mean() не нужно, требуется только реализовать ее.
#
# Номер
# теста
# Входные
# данные
# Выходные
# данные

# 1
#
# print(mean(1.5, True, ['stepik'], 'beegeek', 2.5, (1, 2)))
#
# 2.0
#
# 2
#
# print(mean(-1, 2, 3, 10, ('5')))
#
# 3.5
#
# 3
#
# print(mean(7))
#
# 7.0
#
# 4
#
# print(mean(True, ['stepik'], 'beegeek', (1, 2)))
#
# 0.0
#
# 5
#
# print(mean(1.5, True, ['stepik'], 'beegeek', 2.5, (1, 2)))
#
# 2.0

def mean(*args):
    # Отбираем только int и float (исключая bool, так как bool — подкласс int)
    numbers = [x for x in args if isinstance(x, (int, float)) and not isinstance(x, bool)]

    if not numbers:
        return 0

    return sum(numbers) / len(numbers)
