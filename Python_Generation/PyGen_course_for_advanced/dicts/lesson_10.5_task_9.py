# По категориям 🌶️
#
# Борис хочет сократить свои расходы, и для этого он решил узнать, на что потратил больше всего денег. Борис скачал выписку из банка, в которой хранится информация по всем тратам в этом месяце. Теперь нужно посчитать траты в каждой категории и найти самые «затратные» категории.
#
# Напишите функцию show_top_categories(), которая принимает два аргумента в следующем порядке:
#
#     spendings – список кортежей, в котором каждый кортеж представлен в виде (<категория>, <cумма>)
#     num – целое число, количество категорий с максимальными тратами, которые нужно найти
#
# Функция show_top_categories() должна подсчитать траты по каждой категории и вывести num категорий, траты по которым максимальные в этом месяце. Категории следует вывести в алфавитном порядке, каждую на отдельной строке.
#
# Примечание 1. Категории в списке spendings могут повторяться.
#
# Примечание 2. Гарантируется, что суммы траты в разных категориях не могут совпасть.
#
# Примечание 3. Вызывать функцию show_top_categories() не нужно, требуется только реализовать ее.
#
# Входные данные
# spendings = [
#     ('продукты', 780), ('фитнес', 3000),
#     ('ЖКХ', 11500), ('продукты', 1200),
#     ('такси', 420), ('продукты', 230),
#     ('аптека', 900), ('сантехника', 700),
#     ('товары для дома', 1750),
# ]
# show_top_categories(spendings, 3)
#
# Выходные данные
# ЖКХ
# продукты
# фитнес

def show_top_categories(spendings, num):
    # Подсчёт сумм по категориям
    total = {}
    for category, amount in spendings:
        total[category] = total.get(category, 0) + amount

    # Получаем категории, отсортированные по убыванию суммы
    sorted_by_amount = sorted(total.items(), key=lambda x: x[1], reverse=True)

    # Берём первые `num` категорий (только названия)
    top_categories = [category for category, _ in sorted_by_amount[:num]]

    top_categories.sort()
    for cat in top_categories:
        print(cat)
