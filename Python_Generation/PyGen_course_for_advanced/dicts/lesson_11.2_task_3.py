# Scrabble game
#
# В игре Scrabble каждая буква приносит определенное количество баллов. Общая стоимость слова – сумма баллов его букв. Чем реже буква встречается, тем больше она ценится:
# Баллы 	Буква
# 11 	AA, EE, II, LL, NN, OO, RR, SS, TT, UU
# 22 	DD, GG
# 33 	BB, CC, MM, PP
# 44 	FF, HH, VV, WW, YY
# 55 	KK
# 88 	JJ, XX
# 1010 	QQ, ZZ
#
# Напишите программу подсчета итоговой стоимости введенного слова.
#
# Формат входных данных
# На вход программе подается одно слово в верхнем регистре на английском языке.
#
# Формат выходных данных
# Программа должна вывести суммарную стоимость букв введенного слова.
#
# Примечание. Подробнее про игру можно почитать по ссылке.
#
# Входные данные
# DANSER
#
# Выходные данные
# 7

word = input().strip()

# Создаём словарь букв -> очки
scores = {}
for letters, point in [
    ('AEILNORSTU', 1),
    ('DG', 2),
    ('BCMP', 3),
    ('FHVWY', 4),
    ('K', 5),
    ('JX', 8),
    ('QZ', 10)
]:
    for letter in letters:
        scores[letter] = point

total = sum(scores[letter] for letter in word)
print(total)