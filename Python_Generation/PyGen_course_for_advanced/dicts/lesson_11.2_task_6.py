# Опасный вирус 😈
#
# В файловую систему компьютера, на котором развернута наша ❤️ платформа Stepik, проник опасный вирус и сломал контроль прав доступа к файлам. Говорят, вирус написал один из студентов курса Python для начинающих.
#
# Для каждого файла известно, с какими действиями можно к нему обращаться:
#
#     запись W (write, доступ на запись в файл);
#     чтение R (read, доступ на чтение из файла);
#     запуск X (execute, запуск на исполнение файла).
#
# Напишите программу для восстановления контроля прав доступа к файлам. Ваша программа для каждого запроса должна будет возвращать OK если выполняется допустимая операция, и Access denied, если операция недопустима.
#
# Формат входных данных
# Программа получает на вход количество файлов nn, содержащихся в файловой системе компьютера. Далее идут nn строк, на каждой имя файла и допустимые с ним операции, разделенные символом пробела. В следующей строке записано число mm – количество запросов к файлам, и затем mm строк с запросами вида операция файл. Одному и тому же файлу может быть адресовано любое количество запросов.
#
# Формат выходных данных
# Программа должна вывести для каждого из mm запросов в отдельной строке Access denied или OK.
#
# Входные данные
# 5
# my_pycode.exe W X
# log_n X W R
# ave R
# lucky_m W R
# dnsss.py W
# 6
# execute ave
# read dnsss.py
# write log_n
# execute log_n
# read ave
# write my_pycode.exe
#
# Выходные данные
# Access denied
# Access denied
# OK
# OK
# OK
# OK


op_map = {'write': 'W', 'read': 'R', 'execute': 'X'}
n = int(input())

# Словарь прав доступа: имя файла -> множество разрешённых операций
access = {}
for _ in range(n):
    parts = input().split()
    filename = parts[0]
    ops = set(parts[1:])  # остальное — операции
    access[filename] = ops

# Чтение количества запросов
m = int(input())

# Обработка запросов
for _ in range(m):
    operation, filename = input().split()
    required = op_map[operation]

    if filename in access and required in access[filename]:
        print("OK")
    else:
        print("Access denied")
