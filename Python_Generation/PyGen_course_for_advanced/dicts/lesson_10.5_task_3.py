def is_access_allowed(ip_address, mode, ip_access_lists):
    if mode == 1:
        # Разрешено всё, кроме чёрного списка
        if ip_address in ip_access_lists['black list']:
            return "НЕТ"
        else:
            return "ДА"
    elif mode == 2:
        # Запрещено всё, кроме белого списка
        if ip_address in ip_access_lists['white list']:
            return "ДА"
        else:
            return "НЕТ"