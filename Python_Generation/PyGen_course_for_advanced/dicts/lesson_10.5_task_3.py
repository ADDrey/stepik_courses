# Напишите функцию is_access_allowed(), которая принимает три аргумента в следующем порядке:
#
#     ip_address – строка, ip-адрес, к которому пользователь пытается обратиться
#     mode – натуральное число, режим работы (11 или 22)
#     ip_access_lists – словарь запрещенных/разрешенных ip-адресов, ключами в котором являются строки 'black list' (черный список) и 'white list' (белый список), а значениями – списки запрещенных/разрешенных ip-адресов соответственно
#
# При режиме работы 11 («разрешено все, что не запрещено») разрешен доступ ко всем ip-адресам, которых нет в черном списке (по ключу 'black list'). При режиме работы 22 («запрещено все, что не разрешено») запрещен доступ ко всем ip-адресам, которых нет в белом списке (по ключу 'white list').
#
# Функция is_access_allowed() должна возвращать ДА, если пользователь получает доступ к указанному ip-адресу, или НЕТ в противном случае.
