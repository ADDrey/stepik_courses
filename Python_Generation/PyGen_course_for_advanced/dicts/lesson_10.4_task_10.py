# Для заезда на платную парковку нужно получить талон, для которого формируется некоторый ID, состоящий из цифр. Далее при выезде нужно отсканировать этот талон и оплатить (при необходимости) парковку. Если машина простояла на парковке более 22 часов, то будет взиматься плата 33 ₽/мин за превышенное (22 часа) время. В противном случае плата не взимается.
#
# На вход программе подается число nn, а затем nn строк, каждая в формате:
#
# <ID>: <время въезда>
#
#
#
#
# где <время въезда> в формате hh:mm.
#
# Далее на вход программе подается натуральное число mm, а затем mm строк, каждая в формате:
#
# <ID>: <время выезда>
#
#
#
#
# где <время выезда> в формате hh:mm.
#
# Если машина простояла на парковке более 22 часов, для данного ID программа должна вывести сумму к оплате в следующем формате:
#
# <ID>: <сумма к оплате>₽
#
#
#
#
# Если машина простояла на парковке не более 22 часов, для данного ID нужно вывести текст в следующем формате:
#
# <ID>: плата не взимается
#
#
#
#
# Формат входных данных
# На вход программе подается натуральное число nn, а затем nn строк, далее натуральное число mm, а затем mm строк.
#
# Формат выходных данных
# Программа должна вывести mm строк в соответствии с условием задачи.
#
# Примечание 1. Гарантируется, что для каждой машины ID уникален.
#
# Примечание 2. Выезд с парковки возможен на следующий день, в таком случае учтите переход через 00:00.
#
# Примечание 3. Гарантируется, что каждая машина стоит на парковке не более суток (2424 часов).
#
#
# Входные данные
# 5
# 198351: 14:20
# 976244: 14:22
# 763482: 14:22
# 974311: 14:26
# 187646: 14:29
# 3
# 976244: 14:59
# 974311: 15:03
# 198351: 16:51
#
# Выходные данные
# 976244: плата не взимается
# 974311: плата не взимается
# 198351: 93₽

def time_to_minutes(t):
    h, m = map(int, t.split(':'))
    return h * 60 + m

# Считываем въезды
n = int(input())
entry = {}
for _ in range(n):
    line = input().strip()
    id_part, time_part = line.split(': ')
    entry[id_part] = time_to_minutes(time_part)

# Считываем выезды и обрабатываем
m = int(input())
for _ in range(m):
    line = input().strip()
    id_part, time_part = line.split(': ')
    out_time = time_to_minutes(time_part)
    in_time = entry[id_part]

    # Вычисляем длительность
    if out_time < in_time:
        # Выезд на следующий день
        duration = (24 * 60 - in_time) + out_time
    else:
        duration = out_time - in_time

    if duration > 120:
        extra = duration - 120
        cost = extra * 3
        print(f"{id_part}: {cost}₽")
    else:
        print(f"{id_part}: плата не взимается")
