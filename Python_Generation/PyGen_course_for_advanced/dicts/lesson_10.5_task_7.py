# Функция scrabble()
#
# Напишите функцию scrabble(), которая принимает два аргумента в следующем порядке:
#
#     letters – строка, содержащая произвольный набор букв
#     word – строка, содержащая слово
#
# Функция должна возвращать True, если из переданного набора букв letters можно составить указанное слово word, или False в противном случае.
#
# Примечание 1. При проверке учитывается количество символов, которые нужны для составления слова, и не учитывается их регистр.
#
# Примечание 2. Для составления слова необязательно использовать все буквы из переданного набора.
#
# Примечание 3. Вызывать функцию scrabble() не нужно, требуется только реализовать ее.
#
# Входные данные
# print(scrabble('BEEGEEK', 'geekbee'))
#
# Выходные данные
# True

def scrabble(letters, word):
    letters = letters.lower()
    word = word.lower()

    # Считаем частоты букв в letters
    letter_count = {}
    for ch in letters:
        letter_count[ch] = letter_count.get(ch, 0) + 1

    # Проверяем каждую букву в word
    for ch in word:
        if letter_count.get(ch, 0) == 0:
            return False
        letter_count[ch] -= 1

    return True
