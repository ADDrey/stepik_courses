# Строка запроса 🔗
#
# Query String (строка запроса) – часть URL с передаваемыми на сервер параметрами в виде пары ключ — значение, которые разделены символом равно = и указываются после вопросительного знака ?. Если параметров несколько, то они разделяются амперсандом &.
#
# Например:
#
#     в URL-адресе https://pygen.ru?page=1 строкой запроса является page=1
#     в URL-адресе https://pygen.ru?page=1&per=5&sort=True строкой запроса является page=1&per=5&sort=True
#
# Напишите функцию add_query_string(), которая принимает два аргумента в следующем порядке:
#
#     url – строка с URL-адресом
#     query – словарь с параметрами
#
# Функция должна возвращать URL-адрес, содержащий строку запроса, сформированную из этих параметров.
#
# Примечание. Вызывать функцию add_query_string() не нужно, требуется только реализовать ее.
#
# Входные данные
# print(add_query_string('pygen.ru', {'per': '10', 'page': 1}))
#
# Выходные данные
# pygen.ru?per=10&page=1

def add_query_string(url, query):
    if not query:
        return url
    # Формируем список пар 'key=value'
    pairs = [f"{key}={value}" for key, value in query.items()]
    # Объединяем через '&'
    query_string = "&".join(pairs)
    # Возвращаем URL + '?' + строка запроса
    return f"{url}?{query_string}"