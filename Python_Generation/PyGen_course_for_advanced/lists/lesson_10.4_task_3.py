# Анаграммы 2
#
# На вход программе подаются два предложения. Напишите программу, которая определяет, являются они анаграммами или нет. Ваша программа должна игнорировать регистр символов, знаки препинания и пробелы.
#
# Формат входных данных
# На вход программе подаются два предложения, каждое на отдельной строке.
#
# Формат выходных данных
# Программа должна вывести YES , если предложения – анаграммы и NO в противном случае.
#
# Примечание. Кроме слов в тексте могут присутствовать пробелы и знаки препинания .,!?:;-. Других символов в тексте нет.
#
#  Sample Input 1:
#
# Вижу зверей
# Живу резвей
#
# Sample Output 1:
#
# YES
#
# Sample Input 2:
#
# Когда увидимся
# тогда и свидимся
#
# Sample Output 2:
#
# NO
#
# Sample Input 3:
#
# С мая весной
# сам я не свой
#
# Sample Output 3:
#
# YES

# Чтение предложений
sentence1 = input()
sentence2 = input()

# Функция для извлечения только букв в нижнем регистре
def clean_letters(s):
    return sorted([char.lower() for char in s if char.isalpha()])

# Получаем отсортированные списки букв
letters1 = clean_letters(sentence1)
letters2 = clean_letters(sentence2)

# Сравниваем
if letters1 == letters2:
    print("YES")
else:
    print("NO")
