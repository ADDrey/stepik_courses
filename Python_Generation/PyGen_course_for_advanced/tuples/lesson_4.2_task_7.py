# Вам доступен кортеж countries. Напишите программу, которая выводит количество элементов кортежа countries.
#
# Примечание. Считайте, что кортеж countries уже объявлен в вашей программе, и вы имеете к нему доступ.
#
# Sample Input 1:
#
# countries = ('Romania', 'Poland', 'Estonia', 'Bulgaria', 'Slovakia', 'Slovenia', 'Hungary')
#
# Sample Output 1:
#
# 7
#
# Sample Input 2:
#
# countries = ('Australia', 'Canada', 'USA')
#
# Sample Output 2:
#
# 3

countries = ('Romania', 'Poland', 'Estonia', 'Bulgaria', 'Slovakia', 'Slovenia', 'Hungary')
number = len(countries)
print(number)
